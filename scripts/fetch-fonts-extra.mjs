/**
 * Self-host the label mono face — JetBrains Mono — so no visitor IP is sent
 * to Google's CDN (DSGVO) and fonts load same-origin. Companion to
 * scripts/fetch-fonts.mjs (Poppins 100–600, body + thin display caps); this
 * one APPENDS its faces to assets/fonts/fonts.css and is idempotent (it
 * strips any previous JetBrains Mono lines first, so re-running is safe).
 * (Fraunces/Lora were retired with the thermal redesign — the display face
 * is Poppins Thin/ExtraLight now.)
 *
 * Network goes through `curl` (which honours the environment HTTPS proxy);
 * Node's global fetch does not. Keeps the latin + latin-ext subsets (DE + EN,
 * incl. umlauts/ß). Re-run to refresh. Requires network to Google Fonts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";
const KEEP = new Set(["latin", "latin-ext"]);
const CSS = "assets/fonts/fonts.css";

// JetBrains Mono: three static label weights.
const FAMILIES = [
  { name: "JetBrains Mono", url: "https://fonts.googleapis.com/css2?family=JetBrains+Mono:wght@400;500;600&display=swap" },
];

const curlText = (url) => execFileSync("curl", ["-sS", "-A", UA, url], { encoding: "utf8", maxBuffer: 1e8 });
const curlBin = (url) => execFileSync("curl", ["-sS", "-A", UA, url], { maxBuffer: 1e8 });

let added = [];
for (const fam of FAMILIES) {
  const css = curlText(fam.url);
  const units = css.split(/\/\*\s*/).slice(1); // "subset */ @font-face {...}"
  for (const u of units) {
    const subset = u.slice(0, u.indexOf(" */")).trim();
    if (!KEEP.has(subset)) continue;
    const block = u.slice(u.indexOf("@font-face"));
    const family = (block.match(/font-family:\s*'([^']+)'/) || [])[1];
    const style = (block.match(/font-style:\s*(\w+)/) || [])[1];
    const weight = (block.match(/font-weight:\s*([\d ]+?);/) || [])[1].trim(); // "400" or "400 700"
    const url = (block.match(/src:\s*url\(([^)]+)\)/) || [])[1];
    const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (!family || !url) continue;
    const slug = family.toLowerCase().replace(/\s+/g, "");
    const wTok = weight.replace(/\s+/g, "-");
    const name = `${slug}-${wTok}-${style}-${subset}.woff2`;
    writeFileSync(`assets/fonts/${name}`, curlBin(url));
    added.push(`@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;`
      + `src:url('/assets/fonts/${name}') format('woff2');unicode-range:${range};}`);
    console.log(`${name}  ${(curlBin(url).length / 1024).toFixed(1)}KB  (weight ${weight})`);
  }
}

// Idempotent rewrite: drop any earlier Fraunces / JetBrains Mono lines, keep
// the rest (header + Poppins), then append the freshly fetched faces.
const kept = readFileSync(CSS, "utf8").split("\n")
  .filter((l) => l && !/font-family:'(Fraunces|JetBrains Mono)'/.test(l));
const out = kept.join("\n")
  + "\n/* JetBrains Mono (label mono) — generated by scripts/fetch-fonts-extra.mjs */\n"
  + added.join("\n") + "\n";
writeFileSync(CSS, out);
console.log(`\n${added.length} faces appended → ${CSS}`);
